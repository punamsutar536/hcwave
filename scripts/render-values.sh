#!/usr/bin/env bash
# -----------------------------------------------------------------------------
# Renders deploy/helm/hcwave/values-<env>.generated.yaml from
# deploy/generated/<env>.env (Bicep outputs + Entra app IDs).
# Usage: scripts/render-values.sh <env>
# -----------------------------------------------------------------------------
source "$(dirname "$0")/lib.sh"
ENV="${1:?environment}"
set -a; source "$REPO_ROOT/deploy/generated/${ENV}.env"; set +a
DOMAIN="${HCWAVE_DOMAIN:-${FRONT_DOOR_HOST:-$AGC_FRONTEND_FQDN}}"
API_HOST="${HCWAVE_API_HOST:-api.${DOMAIN}}"
REPORTS_HOST="${HCWAVE_REPORTS_HOST:-reports.${DOMAIN}}"
STAFF_HOST="${HCWAVE_STAFF_HOST:-staff.${DOMAIN}}"
TAG="${IMAGE_TAG:-$(git -C "$REPO_ROOT" rev-parse --short HEAD)}"
# Cloud environments use the staging or prod config profile; the laptop-only
# "dev" profile (console WhatsApp, simulator routes) is never used on Azure.
APP_PROFILE=$([[ "$ENV" == "prod" ]] && echo prod || echo staging)

cat > "$REPO_ROOT/deploy/helm/hcwave/values-${ENV}.generated.yaml" <<VALUES
# Generated by scripts/render-values.sh for ${ENV} – do not commit.
global:
  imageRegistry: ${ACR_LOGIN_SERVER}
image:
  backend: { repository: hcwave/backend, tag: "${TAG}" }
  staffUi: { repository: hcwave/staff-ui, tag: "${TAG}" }
serviceAccount:
  workloadIdentity: { enabled: true, clientId: "${WORKLOAD_CLIENT_ID}" }
env:
  APP_ENV: "${APP_PROFILE}"
  PUBLIC_BASE_URL: "https://${API_HOST}"
  REPORTS_BASE_URL: "https://${REPORTS_HOST}"
  STAFF_UI_ORIGIN: "https://${STAFF_HOST}"
  AZURE_TENANT_ID: "${TENANT_ID}"
  DATABASE_URL: "postgresql+asyncpg://${WORKLOAD_IDENTITY_NAME}@${POSTGRES_HOST}:5432/${POSTGRES_DB}"
  SERVICEBUS_NAMESPACE: "${SERVICEBUS_NAMESPACE}"
  AZURE_STORAGE_ACCOUNT_URL: "${STORAGE_ACCOUNT_URL}"
  ACS_ENDPOINT: "${ACS_ENDPOINT}"
  ACS_SMS_FROM: "${ACS_SMS_FROM:-}"
  EMAIL_SENDER: "${EMAIL_SENDER}"
  AZURE_OPENAI_ENDPOINT: "${AZURE_OPENAI_ENDPOINT}"
  AZURE_SEARCH_ENDPOINT: "${AZURE_SEARCH_ENDPOINT}"
  AZURE_CONTENT_SAFETY_ENDPOINT: "${AZURE_CONTENT_SAFETY_ENDPOINT}"
  AZURE_TRANSLATOR_ENDPOINT: "${AZURE_TRANSLATOR_ENDPOINT}"
  APPLICATIONINSIGHTS_CONNECTION_STRING: "${APPLICATIONINSIGHTS_CONNECTION_STRING}"
  STAFF_API_AUDIENCE: "${STAFF_API_AUDIENCE:-}"
  INTERNAL_API_AUDIENCE: "${INTERNAL_API_AUDIENCE:-}"
  INTERNAL_ALLOWED_CLIENT_IDS: "${LOGICAPP_CLIENT_ID},${FUNCTIONS_CLIENT_ID}"
  DURABLE_FEEDBACK_START_URL: "${DURABLE_FEEDBACK_START_URL}"
  DURABLE_FUNCTIONS_AUDIENCE: "${FUNCTIONS_AUDIENCE:-}"
  DEMO_HOSPITAL_CHANNEL_IDS: "${DEMO_HOSPITAL_CHANNEL_IDS:-}"
secrets:
  azureKeyVault: { keyvaultName: "${KEY_VAULT_NAME}", tenantId: "${TENANT_ID}" }
api:
  internalService: { loadBalancerIP: "${INTERNAL_API_IP}" }
worker:
  keda: { serviceBusNamespace: "${SERVICEBUS_NAMESPACE}" }
staffUi:
  env:
    ENTRA_CLIENT_ID: "${ENTRA_SPA_CLIENT_ID:-}"
    ENTRA_TENANT_ID: "${TENANT_ID}"
    STAFF_API_SCOPE: "${STAFF_API_SCOPE:-}"
    API_BASE_URL: ""
ingress:
  hosts: { api: "${API_HOST}", reports: "${REPORTS_HOST}", staff: "${STAFF_HOST}" }
  gateway:
    annotations: { alb.networking.azure.io/alb-id: "${AGC_ID}" }
    addresses: [ { type: alb.networking.azure.io/alb-frontend, value: "${AGC_FRONTEND}" } ]
    wafSecurityPolicyId: "${AGC_SECURITY_POLICY_ID}"
VALUES
log "wrote deploy/helm/hcwave/values-${ENV}.generated.yaml"
