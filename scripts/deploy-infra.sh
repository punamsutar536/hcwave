#!/usr/bin/env bash
# -----------------------------------------------------------------------------
# Deploys the Azure environment with Bicep and writes the outputs to
# deploy/generated/<env>.env and the Helm overlay values-<env>.generated.yaml.
# Usage: HCWAVE_ADMIN_GROUP_ID=<guid> scripts/deploy-infra.sh <dev|staging|prod> [--what-if]
# -----------------------------------------------------------------------------
source "$(dirname "$0")/lib.sh"
require az jq
ENV="${1:?environment}"; MODE="${2:-}"
: "${HCWAVE_ADMIN_GROUP_ID:?export HCWAVE_ADMIN_GROUP_ID (Entra group for AKS/PostgreSQL admins)}"
PARAMS="$REPO_ROOT/infra/bicep/parameters/${ENV}.bicepparam"
[[ -f "$PARAMS" ]] || die "no parameter file $PARAMS (copy dev.bicepparam)"

if [[ "$MODE" == "--what-if" ]]; then
  az deployment sub what-if --location centralindia --name "hcwave-${ENV}" \
    --template-file "$REPO_ROOT/infra/bicep/main.bicep" --parameters "$PARAMS"
  exit 0
fi

log "deploying hcwave-${ENV} (this takes 30–60 minutes the first time)"
az deployment sub create --location centralindia --name "hcwave-${ENV}" \
  --template-file "$REPO_ROOT/infra/bicep/main.bicep" --parameters "$PARAMS" -o none

OUT_DIR="$REPO_ROOT/deploy/generated"; mkdir -p "$OUT_DIR"
outputs=$(az deployment sub show --name "hcwave-${ENV}" --query properties.outputs -o json)
get() { jq -r ".${1}.value" <<<"$outputs"; }

cat > "$OUT_DIR/${ENV}.env" <<ENVFILE
# Generated by scripts/deploy-infra.sh – do not commit.
RESOURCE_GROUP=$(get resourceGroupName)
AKS_NAME=$(get aksName)
ACR_NAME=$(get acrName)
ACR_LOGIN_SERVER=$(get acrLoginServer)
KEY_VAULT_NAME=$(get keyVaultName)
TENANT_ID=$(get tenantId)
WORKLOAD_CLIENT_ID=$(get workloadIdentityClientId)
WORKLOAD_IDENTITY_NAME=$(get workloadIdentityName)
ALB_CONTROLLER_CLIENT_ID=$(get albControllerClientId)
LOGICAPP_CLIENT_ID=$(get logicAppClientId)
FUNCTIONS_CLIENT_ID=$(get functionsClientId)
AGC_ID=$(get agcId)
AGC_FRONTEND=$(get agcFrontendName)
AGC_FRONTEND_FQDN=$(get agcFrontendFqdn)
AGC_SECURITY_POLICY_ID=$(get agcSecurityPolicyId)
FRONT_DOOR_HOST=$(get frontDoorHostName)
POSTGRES_HOST=$(get postgresHost)
POSTGRES_DB=$(get postgresDatabase)
SERVICEBUS_NAMESPACE=$(get serviceBusNamespace)
STORAGE_ACCOUNT_URL=$(get storageAccountUrl)
ACS_ENDPOINT=$(get acsEndpoint)
EMAIL_SENDER=$(get acsEmailSender)
AZURE_OPENAI_ENDPOINT=$(get openAiEndpoint)
AZURE_SEARCH_ENDPOINT=$(get searchEndpoint)
AZURE_CONTENT_SAFETY_ENDPOINT=$(get contentSafetyEndpoint)
AZURE_TRANSLATOR_ENDPOINT=$(get translatorEndpoint)
APPLICATIONINSIGHTS_CONNECTION_STRING=$(get appInsightsConnectionString)
INTERNAL_API_IP=$(get internalApiIp)
DURABLE_FEEDBACK_START_URL=$(get durableFeedbackStartUrl)
LOGIC_APP_NAME=$(get logicAppName)
FUNCTION_APP_NAME=$(get functionAppName)
ENVFILE
log "wrote $OUT_DIR/${ENV}.env"
"$REPO_ROOT/scripts/render-values.sh" "$ENV"
